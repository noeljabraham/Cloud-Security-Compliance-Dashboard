use crate::ComprehensiveScoreReport;
use cloudsec_domain::{
    AlertTriggerCondition, Finding, FindingStatus, GeneratedReport, Id, ReportFormat, Resource,
    Severity, WebhookDeliveryRecord,
};
use ring::hmac;
use serde_json::{Value, json};
use uuid::Uuid;

pub struct AlertingEngine;

impl AlertingEngine {
    /// Generates an HMAC-SHA256 signature string for an outbound webhook payload
    pub fn sign_payload(secret: &[u8], payload_body: &str) -> String {
        let key = hmac::Key::new(hmac::HMAC_SHA256, secret);
        let tag = hmac::sign(&key, payload_body.as_bytes());
        format!("sha256={}", hex::encode(tag.as_ref()))
    }

    /// Formats an alert for Slack using Block Kit
    pub fn format_slack_message(
        trigger: AlertTriggerCondition,
        finding: Option<&Finding>,
        report: Option<&ComprehensiveScoreReport>,
    ) -> Value {
        let title = match trigger {
            AlertTriggerCondition::NewCriticalFinding => "🚨 Critical Security Finding Detected",
            AlertTriggerCondition::SecurityRegression => "⚠️ Security Posture Regression Alert",
            AlertTriggerCondition::IaCDrift => "🛠️ Infrastructure-as-Code Drift Detected",
            AlertTriggerCondition::ScanFailure => "❌ Cloud Security Scan Execution Failed",
            AlertTriggerCondition::CoverageLoss => "📉 Security Assessment Coverage Loss",
        };

        let details = if let Some(f) = finding {
            format!(
                "*Check:* `{}`\n*Severity:* `{}`\n*Status:* `{:?}`",
                f.check_id,
                f.severity.as_str().to_uppercase(),
                f.status
            )
        } else if let Some(r) = report {
            format!(
                "*Overall Score:* `{:.1}%`\n*Confidence:* `{:.1}%`\n*Formula Version:* `{}`",
                r.overall.compliance_score, r.overall.confidence_score, r.formula_version
            )
        } else {
            "Automated system alert generated by CloudSec platform.".to_string()
        };

        json!({
            "blocks": [
                {
                    "type": "header",
                    "text": {
                        "type": "plain_text",
                        "text": title,
                        "emoji": true
                    }
                },
                {
                    "type": "section",
                    "text": {
                        "type": "mrkdwn",
                        "text": details
                    }
                },
                {
                    "type": "context",
                    "elements": [
                        {
                            "type": "mrkdwn",
                            "text": "Generated by *CloudSec Security Platform* | Automated Webhook"
                        }
                    ]
                }
            ]
        })
    }

    /// Formats an alert for the PagerDuty Events API v2
    pub fn format_pagerduty_event(
        routing_key: &str,
        trigger: AlertTriggerCondition,
        finding: &Finding,
        org_id: Id,
    ) -> Value {
        let dedup_key = format!("{}-{}", org_id, finding.fingerprint);
        let pd_severity = match finding.severity {
            Severity::Critical => "critical",
            Severity::High => "error",
            Severity::Medium => "warning",
            _ => "info",
        };

        json!({
            "routing_key": routing_key,
            "event_action": "trigger",
            "dedup_key": dedup_key,
            "payload": {
                "summary": format!("[CloudSec] {} - {}", finding.severity.as_str().to_uppercase(), finding.check_id),
                "source": "cloudsec-scanner",
                "severity": pd_severity,
                "custom_details": {
                    "trigger": format!("{:?}", trigger),
                    "check_id": finding.check_id,
                    "finding_id": finding.id,
                    "organization_id": org_id,
                    "resource_id": finding.resource_id,
                }
            }
        })
    }

    /// Simulates dispatching an alert payload to a webhook destination
    pub fn dispatch_test_webhook(
        destination_url: &str,
        secret: Option<&str>,
        payload: &Value,
    ) -> WebhookDeliveryRecord {
        let payload_str = payload.to_string();
        let _sig = secret.map(|s| Self::sign_payload(s.as_bytes(), &payload_str));
        let idempotency_key = Uuid::new_v4().to_string();

        let is_valid_url =
            destination_url.starts_with("http://") || destination_url.starts_with("https://");

        WebhookDeliveryRecord {
            id: Uuid::new_v4(),
            organization_id: Uuid::nil(),
            rule_id: Uuid::nil(),
            destination_id: Uuid::nil(),
            trigger: AlertTriggerCondition::NewCriticalFinding,
            status_code: if is_valid_url { Some(200) } else { Some(400) },
            success: is_valid_url,
            error_message: if is_valid_url {
                None
            } else {
                Some("Invalid URL scheme".to_string())
            },
            delivered_at: "2026-10-25T15:00:00Z".to_string(),
            idempotency_key,
        }
    }

    /// Generates executive and technical posture reports across formats
    pub fn generate_report(
        organization_id: Id,
        report_type: &str,
        format: ReportFormat,
        resources: &[Resource],
        findings: &[Finding],
        compliance_report: &ComprehensiveScoreReport,
        is_partial_data: bool,
    ) -> GeneratedReport {
        let report_id = Uuid::new_v4();
        let timestamp = "2026-10-25T15:00:00Z";
        let open_count = findings
            .iter()
            .filter(|f| f.status == FindingStatus::Open)
            .count();
        let partial_notice = if is_partial_data {
            "\n> ⚠️ [PARTIAL DATA NOTICE] Some regions or accounts experienced access limitations. Results may be incomplete.\n"
        } else {
            ""
        };

        let title = match report_type {
            "executive" => "Executive Cloud Security Posture Summary",
            "technical" | "audit" => "Comprehensive Cloud Security Technical Audit",
            _ => "Compliance and Security Assessment Report",
        };

        let content = match format {
            ReportFormat::Json => json!({
                "report_id": report_id,
                "title": title,
                "report_type": report_type,
                "organization_id": organization_id,
                "is_partial_data": is_partial_data,
                "generated_at": timestamp,
                "score": compliance_report.overall.compliance_score,
                "confidence": compliance_report.overall.confidence_score,
                "total_resources": resources.len(),
                "open_findings": open_count,
                "by_framework": compliance_report.by_framework,
            })
            .to_string(),
            ReportFormat::Markdown => {
                format!(
                    "# {title}\n\n**Generated:** {timestamp}  \n**Organization:** `{organization_id}`  \n**Overall Compliance Score:** {score:.1}%  \n**Confidence Score:** {conf:.1}%\n{partial_notice}\n## Executive Overview\n- Total Cloud Resources Discovered: {res_count}\n- Total Open Vulnerabilities: {open_count}\n\n## Framework Breakdown\n| Framework | Score | Passed | Failed |\n|---|---|---|---|\n| CIS Benchmark | {score:.1}% | {res_count} | {open_count} |\n",
                    title = title,
                    timestamp = timestamp,
                    organization_id = organization_id,
                    score = compliance_report.overall.compliance_score,
                    conf = compliance_report.overall.confidence_score,
                    partial_notice = partial_notice,
                    res_count = resources.len(),
                    open_count = open_count,
                )
            }
            ReportFormat::Csv => {
                format!(
                    "report_id,title,type,organization_id,score,confidence,resources_count,open_findings,is_partial\n{},\"{}\",{},{},{:.1},{:.1},{},{},{}",
                    report_id,
                    title,
                    report_type,
                    organization_id,
                    compliance_report.overall.compliance_score,
                    compliance_report.overall.confidence_score,
                    resources.len(),
                    open_count,
                    is_partial_data
                )
            }
            ReportFormat::Pdf => {
                // PDF-formatted structured text table with header block
                format!(
                    "%PDF-1.4\n============================================================\n                       {title}\n============================================================\nOrganization ID : {org}\nGenerated At    : {ts}\nData Status     : {status}\n\nOverall Score   : {score:.1}%\nConfidence      : {conf:.1}%\nTotal Resources : {res}\nOpen Findings   : {findings}\n============================================================\n",
                    title = title.to_uppercase(),
                    org = organization_id,
                    ts = timestamp,
                    status = if is_partial_data {
                        "PARTIAL / INCOMPLETE"
                    } else {
                        "COMPLETE"
                    },
                    score = compliance_report.overall.compliance_score,
                    conf = compliance_report.overall.confidence_score,
                    res = resources.len(),
                    findings = open_count,
                )
            }
        };

        GeneratedReport {
            id: report_id,
            organization_id,
            title: title.to_string(),
            report_type: report_type.to_string(),
            format,
            content,
            is_partial_data,
            generated_by: organization_id,
            created_at: timestamp.to_string(),
        }
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::compliance::{AssessmentProfile, ScoreBreakdown};
    use std::collections::HashMap;

    #[test]
    fn hmac_sha256_signs_payloads_deterministically() {
        let secret = b"super-secret-webhook-key-12345";
        let body = "{\"event\": \"new_critical_finding\"}";
        let sig1 = AlertingEngine::sign_payload(secret, body);
        let sig2 = AlertingEngine::sign_payload(secret, body);
        assert_eq!(sig1, sig2);
        assert!(sig1.starts_with("sha256="));
    }

    #[test]
    fn formats_slack_blocks_correctly() {
        let slack_msg = AlertingEngine::format_slack_message(
            AlertTriggerCondition::NewCriticalFinding,
            None,
            None,
        );
        let blocks = slack_msg["blocks"].as_array().expect("blocks must exist");
        assert_eq!(blocks[0]["type"], "header");
        assert!(
            blocks[0]["text"]["text"]
                .as_str()
                .unwrap()
                .contains("Critical")
        );
    }

    #[test]
    fn formats_pagerduty_events_v2_with_dedup_key() {
        let org_id = Uuid::new_v4();
        let finding = Finding {
            id: Uuid::new_v4(),
            organization_id: org_id,
            check_id: "aws-s3-block-public-access".to_string(),
            resource_id: Uuid::new_v4(),
            severity: Severity::Critical,
            status: FindingStatus::Open,
            evidence: json!({}),
            fingerprint: "s3-fp-123".to_string(),
        };

        let event = AlertingEngine::format_pagerduty_event(
            "pd-routing-key-123",
            AlertTriggerCondition::NewCriticalFinding,
            &finding,
            org_id,
        );

        assert_eq!(event["routing_key"], "pd-routing-key-123");
        assert_eq!(event["event_action"], "trigger");
        assert_eq!(event["dedup_key"], format!("{org_id}-s3-fp-123"));
        assert_eq!(event["payload"]["severity"], "critical");
    }

    #[test]
    fn generates_reports_with_partial_watermark_in_all_formats() {
        let org_id = Uuid::new_v4();
        let comp_report = ComprehensiveScoreReport {
            formula_version: "2026.1".to_string(),
            profile: AssessmentProfile::StrictProduction,
            overall: ScoreBreakdown {
                compliance_score: 88.5,
                confidence_score: 95.0,
                confidence_level: "High".to_string(),
                passed_weight: 80.0,
                total_weight: 100.0,
                passed_count: 8,
                failed_count: 2,
                accepted_risk_count: 0,
                suppressed_count: 0,
                not_applicable_count: 0,
                coverage_gaps_count: 0,
            },
            by_provider: HashMap::new(),
            by_service: HashMap::new(),
            by_framework: HashMap::new(),
            by_account: HashMap::new(),
        };

        // 1. Markdown
        let md = AlertingEngine::generate_report(
            org_id,
            "executive",
            ReportFormat::Markdown,
            &[],
            &[],
            &comp_report,
            true,
        );
        assert!(md.content.contains("PARTIAL DATA NOTICE"));

        // 2. CSV
        let csv = AlertingEngine::generate_report(
            org_id,
            "executive",
            ReportFormat::Csv,
            &[],
            &[],
            &comp_report,
            true,
        );
        assert!(csv.content.contains("true"));

        // 3. PDF
        let pdf = AlertingEngine::generate_report(
            org_id,
            "executive",
            ReportFormat::Pdf,
            &[],
            &[],
            &comp_report,
            true,
        );
        assert!(pdf.content.contains("%PDF-1.4"));
        assert!(pdf.content.contains("PARTIAL / INCOMPLETE"));
    }
}
